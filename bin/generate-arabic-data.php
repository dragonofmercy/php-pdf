<?php

declare(strict_types=1);

/**
 * Generates src/Text/Arabic/ArabicShapingData.php from the Unicode UCD files
 * under build/bin/ucd-source/ (ArabicShaping.txt + UnicodeData.txt).
 *
 *  - JOINING_TYPES: codepoint => one of R L D C T (joining type). Listed
 *    entries from ArabicShaping.txt, plus the standard default that an unlisted
 *    char of general category Mn/Me/Cf is Transparent (T). Default-U entries are
 *    dropped; lookup defaults to 'U'.
 *  - FORMS: base codepoint => [isolated, initial, medial, final] presentation
 *    form codepoints (0 where a form does not exist), from the
 *    <isolated|initial|medial|final> decompositions in UnicodeData.txt.
 *  - LAM_ALEF: alef codepoint => [ligature_isolated, ligature_final], restricted
 *    to the four mandatory alef variants (0622 madda, 0623 hamza-above, 0625
 *    hamza-below, 0627 plain), from the <isolated|final> 0644 06xx decompositions.
 *
 * Usage: php build/bin/generate-arabic-data.php
 */

const SHAPING_FILE = __DIR__ . '/ucd-source/ArabicShaping.txt';
const UNICODE_FILE = __DIR__ . '/ucd-source/UnicodeData.txt';
const OUT_FILE = __DIR__ . '/../src/Text/Arabic/ArabicShapingData.php';

$shapingLines = file(SHAPING_FILE, FILE_IGNORE_NEW_LINES);
$unicodeLines = file(UNICODE_FILE, FILE_IGNORE_NEW_LINES);
if ($shapingLines === false || $unicodeLines === false) {
    fwrite(STDERR, "Cannot read UCD source files\n");
    exit(1);
}

// --- joining types from ArabicShaping.txt ("0628; BEH; D; LAM")
/** @var array<int,string> $joining */
$joining = [];
foreach ($shapingLines as $line) {
    $hash = strpos($line, '#');
    if ($hash !== false) {
        $line = substr($line, 0, $hash);
    }
    $line = trim($line);
    if ($line === '') {
        continue;
    }
    $parts = array_map('trim', explode(';', $line));
    if (count($parts) < 3 || !preg_match('/^[0-9A-Fa-f]+$/', $parts[0])) {
        continue;
    }
    $joining[(int) hexdec($parts[0])] = $parts[2]; // field index 2 = joining type
}

// --- presentation forms + lam-alef + Mn/Me/Cf transparency from UnicodeData.txt
/** @var array<int,array<int,int>> $forms base => [pos => form] (pos 0..3) */
$forms = [];
/** @var array<int,array<int,int>> $lamAlef alef => [pos => form] (pos 0 iso, 1 fin) */
$lamAlef = [];
$posIndex = ['isolated' => 0, 'initial' => 1, 'medial' => 2, 'final' => 3];

foreach ($unicodeLines as $line) {
    $f = explode(';', $line);
    if (count($f) < 6 || $f[0] === '') {
        continue;
    }
    $cp = (int) hexdec($f[0]);
    $category = $f[2];
    $decomp = $f[5];

    // Default transparency: unlisted Mn/Me/Cf marks are Transparent.
    if (!isset($joining[$cp]) && in_array($category, ['Mn', 'Me', 'Cf'], true)) {
        $joining[$cp] = 'T';
    }

    if ($decomp === '' || $decomp[0] !== '<') {
        continue;
    }
    if (!preg_match('/^<(\w+)>\s+(.+)$/', $decomp, $m)) {
        continue;
    }
    $tag = $m[1];
    if (!isset($posIndex[$tag])) {
        continue;
    }
    $bases = array_map(static fn(string $h): int => (int) hexdec($h), preg_split('/\s+/', trim($m[2])) ?: []);

    if (count($bases) === 1) {
        $base = $bases[0];
        if ($base < 0x0600 || $base > 0x06FF) {
            continue;
        }
        $forms[$base] ??= [0, 0, 0, 0];
        $forms[$base][$posIndex[$tag]] = $cp;
    } elseif (
        count($bases) === 2
        && $bases[0] === 0x0644
        && in_array($bases[1], [0x0622, 0x0623, 0x0625, 0x0627], true) // mandatory lam-alef: madda, hamza-above, hamza-below, plain
        && ($tag === 'isolated' || $tag === 'final')
    ) {
        $alef = $bases[1];
        $lamAlef[$alef] ??= [0, 0];
        $lamAlef[$alef][$tag === 'isolated' ? 0 : 1] = $cp;
    }
}

ksort($joining);
ksort($forms);
ksort($lamAlef);

// Drop default-U joining entries to keep the table compact.
$joining = array_filter($joining, static fn(string $t): bool => $t !== 'U');

$php = "<?php\n\ndeclare(strict_types=1);\n\n";
$php .= "namespace DragonOfMercy\\PhpPdf\\Text\\Arabic;\n\n";
$php .= "/**\n * GENERATED by bin/generate-arabic-data.php from Unicode 15.1.0\n";
$php .= " * ArabicShaping.txt + UnicodeData.txt. Do not edit by hand.\n */\n";
$php .= "final class ArabicShapingData\n{\n";

$php .= "    /** @var array<int, string> codepoint => joining type (R/L/D/C/T); default 'U' */\n";
$php .= "    public const array JOINING_TYPES = [\n";
foreach ($joining as $cp => $type) {
    $php .= sprintf("        0x%04X => '%s',\n", $cp, $type);
}
$php .= "    ];\n\n";

$php .= "    /** @var array<int, list<int>> base => [isolated, initial, medial, final] (0 if absent) */\n";
$php .= "    public const array FORMS = [\n";
foreach ($forms as $base => $set) {
    $php .= sprintf("        0x%04X => [0x%04X, 0x%04X, 0x%04X, 0x%04X],\n", $base, $set[0], $set[1], $set[2], $set[3]);
}
$php .= "    ];\n\n";

$php .= "    /** @var array<int, list<int>> alef => [ligature_isolated, ligature_final] */\n";
$php .= "    public const array LAM_ALEF = [\n";
foreach ($lamAlef as $alef => $set) {
    $php .= sprintf("        0x%04X => [0x%04X, 0x%04X],\n", $alef, $set[0], $set[1]);
}
$php .= "    ];\n}\n";

if (!is_dir(dirname(OUT_FILE)) && !mkdir(dirname(OUT_FILE), 0755, true)) {
    fwrite(STDERR, "Cannot create output dir\n");
    exit(1);
}
file_put_contents(OUT_FILE, $php);
echo sprintf("Wrote %d joining, %d forms, %d lam-alef to %s\n", count($joining), count($forms), count($lamAlef), OUT_FILE);
