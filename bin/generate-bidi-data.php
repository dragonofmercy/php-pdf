<?php

declare(strict_types=1);

/**
 * Generates the generated Bidi data classes from the Unicode UCD source files
 * under build/bin/ucd-source/:
 *
 *  - BidiClassData.php   from DerivedBidiClass.txt (sorted [start, end, class]
 *    triples for every range whose class is NOT "L"; "L" is the implicit
 *    default returned for any codepoint not covered by a range, which keeps the
 *    table compact, since Latin and most of the BMP are L and thus omitted).
 *  - BidiBracketData.php from BidiBrackets.txt (the full set of paired-bracket
 *    open => close codepoints used by rule N0 / BD16).
 *
 * Usage: php build/bin/generate-bidi-data.php
 */

const UCD_FILE = __DIR__ . '/ucd-source/DerivedBidiClass.txt';
const OUT_FILE = __DIR__ . '/../src/Text/Bidi/BidiClassData.php';
const BRACKETS_FILE = __DIR__ . '/ucd-source/BidiBrackets.txt';
const BRACKETS_OUT_FILE = __DIR__ . '/../src/Text/Bidi/BidiBracketData.php';

$lines = file(UCD_FILE, FILE_IGNORE_NEW_LINES);
if ($lines === false) {
    fwrite(STDERR, "Cannot read " . UCD_FILE . "\n");
    exit(1);
}

/** @var list<array{0:int,1:int,2:string}> $ranges */
$ranges = [];
foreach ($lines as $line) {
    $hash = strpos($line, '#');
    if ($hash !== false) {
        $line = substr($line, 0, $hash);
    }
    $line = trim($line);
    if ($line === '') {
        continue;
    }
    // "0041..005A ; L" or "00AA ; L"
    if (!preg_match('/^([0-9A-Fa-f]+)(?:\.\.([0-9A-Fa-f]+))?\s*;\s*([A-Za-z]+)$/', $line, $m)) {
        continue;
    }
    $start = (int) hexdec($m[1]);
    $end = ($m[2] ?? '') !== '' ? (int) hexdec($m[2]) : $start;
    $class = $m[3];
    if ($class === 'L') {
        continue;
    }
    $ranges[] = [$start, $end, $class];
}

usort($ranges, static fn(array $a, array $b): int => $a[0] <=> $b[0]);

$php = "<?php\n\ndeclare(strict_types=1);\n\n";
$php .= "namespace DragonOfMercy\\PhpPdf\\Text\\Bidi;\n\n";
$php .= "/**\n * GENERATED by bin/generate-bidi-data.php from Unicode 15.1.0\n";
$php .= " * DerivedBidiClass.txt. Do not edit by hand.\n *\n";
$php .= " * Sorted [start, end, bidiClass] ranges for non-L codepoints. Any\n";
$php .= " * codepoint not covered by a range defaults to class 'L'.\n */\n";
$php .= "final class BidiClassData\n{\n";
$php .= "    /** @var list<array{0:int,1:int,2:string}> */\n";
$php .= "    public const array RANGES = [\n";
foreach ($ranges as $r) {
    $php .= sprintf("        [0x%04X, 0x%04X, '%s'],\n", $r[0], $r[1], $r[2]);
}
$php .= "    ];\n}\n";

if (!is_dir(dirname(OUT_FILE)) && !mkdir(dirname(OUT_FILE), 0755, true)) {
    fwrite(STDERR, "Cannot create output dir: " . dirname(OUT_FILE) . "\n");
    exit(1);
}

file_put_contents(OUT_FILE, $php);
echo "Wrote " . count($ranges) . " ranges to " . OUT_FILE . "\n";

// --- BidiBracketData.php (rule N0 / BD16 paired brackets) ---

$bracketLines = file(BRACKETS_FILE, FILE_IGNORE_NEW_LINES);
if ($bracketLines === false) {
    fwrite(STDERR, "Cannot read " . BRACKETS_FILE . "\n");
    exit(1);
}

/** @var array<int, int> $pairs open codepoint => close codepoint */
$pairs = [];
foreach ($bracketLines as $line) {
    $hash = strpos($line, '#');
    if ($hash !== false) {
        $line = substr($line, 0, $hash);
    }
    $line = trim($line);
    if ($line === '') {
        continue;
    }
    // "0028; 0029; o" (open) or "0029; 0028; c" (close)
    if (!preg_match('/^([0-9A-Fa-f]+)\s*;\s*([0-9A-Fa-f]+)\s*;\s*([oc])$/', $line, $m)) {
        continue;
    }
    if ($m[3] !== 'o') {
        continue;
    }
    $open = (int) hexdec($m[1]);
    $close = (int) hexdec($m[2]);
    $pairs[$open] = $close;
}
ksort($pairs);

$php = "<?php\n\ndeclare(strict_types=1);\n\n";
$php .= "namespace DragonOfMercy\\PhpPdf\\Text\\Bidi;\n\n";
$php .= "/**\n * GENERATED by bin/generate-bidi-data.php from Unicode 15.1.0\n";
$php .= " * BidiBrackets.txt. Do not edit by hand.\n *\n";
$php .= " * Paired-bracket open codepoint => matching close codepoint, used by\n";
$php .= " * rule N0 (BD14/BD15/BD16) of the Unicode Bidirectional Algorithm.\n */\n";
$php .= "final class BidiBracketData\n{\n";
$php .= "    /** @var array<int, int> */\n";
$php .= "    public const array OPEN_TO_CLOSE = [\n";
foreach ($pairs as $open => $close) {
    $php .= sprintf("        0x%04X => 0x%04X,\n", $open, $close);
}
$php .= "    ];\n}\n";

file_put_contents(BRACKETS_OUT_FILE, $php);
echo "Wrote " . count($pairs) . " bracket pairs to " . BRACKETS_OUT_FILE . "\n";
